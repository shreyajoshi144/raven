// Safe DOM helpers. Untrusted strings are only ever assigned via textContent / setAttribute for known-safe attributes.
export function el(tag, props = {}, ...children) {
  const node = document.createElement(tag);
  for (const [k, v] of Object.entries(props || {})) {
    if (v == null || v === false) continue;
    if (k === 'class') node.className = v;
    else if (k === 'text') node.textContent = v;
    else if (k === 'on') for (const [ev, fn] of Object.entries(v)) node.addEventListener(ev, fn);
    else if (k === 'dataset') Object.assign(node.dataset, v);
    else if (k.startsWith('aria-') || k === 'role' || k === 'for' || k === 'id' || k === 'type' || k === 'name' || k === 'value' || k === 'placeholder' ||
             k === 'href' || k === 'rel' || k === 'target' || k === 'title' || k === 'disabled' || k === 'checked' || k === 'autocomplete' || k === 'required' ||
             k === 'maxlength' || k === 'style' || k === 'novalidate' || k === 'minlength' || k === 'rows' || k === 'tabindex' || k === 'lang' || k === 'download' || k === 'open') {
      if (k === 'disabled' || k === 'checked' || k === 'required') node[k] = !!v; else node.setAttribute(k, v === true ? '' : String(v));
    }
  }
  append(node, children);
  return node;
}
function append(node, children) {
  for (const c of children.flat(Infinity)) {
    if (c == null || c === false) continue;
    node.appendChild(c instanceof Node ? c : document.createTextNode(String(c)));
  }
}
export function clear(node) { while (node.firstChild) node.removeChild(node.firstChild); return node; }
export function mount(node, ...children) { clear(node); append(node, children); return node; }

export function toast(message, kind = '') {
  const box = document.getElementById('toasts');
  const t = el('div', { class: 'toast ' + kind, text: message });
  box.appendChild(t);
  setTimeout(() => t.remove(), kind === 'bad' ? 8000 : 4000);
}

export function spinner(label = 'Loading…') { return el('span', { class: 'muted', role: 'status' }, el('span', { class: 'spinner', 'aria-hidden': 'true' }), ' ', label); }

export function badge(text, kind = 'neutral', title) { return el('span', { class: 'badge ' + kind, text, title }); }

export function fmtDate(iso) { return iso ? new Date(iso).toLocaleString() : '—'; }
export function fmtDuration(sec) {
  if (sec == null) return '—';
  if (sec < 60) return `${Math.round(sec)}s`;
  return `${Math.floor(sec / 60)}m ${Math.round(sec % 60)}s`;
}
export function fmtBytes(n) { return n < 1024 ? `${n} B` : n < 1048576 ? `${(n / 1024).toFixed(1)} KB` : `${(n / 1048576).toFixed(1)} MB`; }
export function shortSha(s) { return (s || '').slice(0, 7); }
export function debounce(fn, ms = 250) { let t; return (...a) => { clearTimeout(t); t = setTimeout(() => fn(...a), ms); }; }

export const STATUS_META = {
  QUEUED: ['Queued', 'neutral'], FETCHING: ['Fetching repository', 'info'], PARSING: ['Parsing source', 'info'], BUILDING_GRAPH: ['Building graph', 'info'],
  GENERATING_DOCS: ['Generating documentation', 'info'], READY: ['Ready', 'ok'], RETRYING: ['Retrying after a temporary error', 'warn'],
  FAILED: ['Failed', 'bad'], CANCELLED: ['Cancelled', 'neutral'],
};
export const PIPELINE = ['QUEUED', 'FETCHING', 'PARSING', 'BUILDING_GRAPH', 'GENERATING_DOCS', 'READY'];
export function statusBadge(s) {
  const [t, k] = STATUS_META[s] || [s, 'neutral'];
  return el('span', { class: 'badge ' + k + (isActive(s) ? ' live' : '') }, el('span', { class: 'dot' }), t);
}
export const isActive = (s) => !['READY', 'FAILED', 'CANCELLED'].includes(s);

export function resolutionBadge(r) {
  const m = { verified_static: ['verified', 'ok', 'Directly supported by source syntax'], inferred: ['inferred', 'warn', 'Heuristic — not proven'], unresolved: ['unresolved', 'bad', 'A reference exists but its target could not be determined statically'] }[r] || [r, 'neutral', ''];
  return badge(m[0], m[1], m[2]);
}
export function sourceLabel(src) { return src === 'ai' ? badge('AI explanation', 'info', 'Generated by a language model from analyzed source; verify against the code') : badge('static summary', 'neutral', 'Derived deterministically from static analysis'); }
