@dataclass
class FileDecision:
    kind: str  # python | support | env_template | other | excluded
    reason: str | None = None


def _matches(name: str, patterns: list[str]) -> bool:
    low = name.lower()
    return any(fnmatch.fnmatch(low, p) for p in patterns)


def is_safe_member_path(path: str) -> bool:
    if not path or path.startswith("/") or "\\" in path or "\x00" in path:
        return False
    parts = PurePosixPath(path).parts
    return not any(p in ("..", "") for p in parts) and len(path) <= 1000


def classify_path(path: str) -> FileDecision:
    """Decide how a repository path is handled before reading content."""
    p = PurePosixPath(path)
    parts = p.parts
    for part in parts[:-1]:
        low = part.lower()
        if low in EXCLUDED_DIRS:
            return FileDecision("excluded", EXCLUDED_DIRS[low])
        if low.endswith(".egg-info"):
            return FileDecision("excluded", "build_artifact")
    name = p.name
    low = name.lower()
    if low in ENV_TEMPLATE_NAMES:
        return FileDecision("env_template")
    if low in LOCKFILE_NAMES or low.endswith(".lock"):
        return FileDecision("excluded", "lockfile")
    if _matches(name, SECRET_FILE_PATTERNS):
        return FileDecision("excluded", "secret_file")
    ext = p.suffix.lower()
    if ext in BINARY_EXTENSIONS:
        return FileDecision("excluded", "binary")
    if low.endswith("_pb2.py") or low.endswith("_pb2_grpc.py") or low.endswith(".pyi"):
        return FileDecision("excluded", "generated")
    if ext == ".py":
        return FileDecision("python")
    if ext in WEB_EXTS:
        if low.endswith((".min.js", ".min.css", ".bundle.js", ".chunk.js", ".d.ts")) or re.search(r"[.-][0-9a-f]{8,}\.(js|css)$", low):
            return FileDecision("excluded", "generated")
        return FileDecision("web")
    rel_lower = "/".join(x.lower() for x in parts)
    if _matches(name, SUPPORT_FILE_PATTERNS) or _matches(rel_lower, ["*/requirements/*.txt"]):
        return FileDecision("support")
    return FileDecision("other")


def looks_binary(data: bytes) -> bool:
    return b"\x00" in data[:8192]


def looks_generated(text: str) -> bool:
    head = "\n".join(text.split("\n", 6)[:6]).lower()
    return any(m in head for m in GENERATED_MARKERS)


@dataclass
class InventoryStats:
    considered: int = 0
    python_found: int = 0
    python_analyzed: int = 0
    web_found: int = 0
    web_analyzed: int = 0
    web_bytes: int = 0
    excluded: dict[str, int] = field(default_factory=dict)
    total_source_bytes: int = 0

    def exclude(self, reason: str) -> None:
        self.excluded[reason] = self.excluded.get(reason, 0) + 1


def looks_minified(text: str) -> bool:
    """Minified/bundled output: a very long line or a very high average line length."""
    lines = text.split("\n")
    longest = max((len(x) for x in lines[:400]), default=0)
    return longest > 1500 or (len(text) > 5000 and len(text) / max(1, len(lines)) > 250)


def count_lines(text: str) -> int:
    """Number of lines as an editor shows them: a final newline ends the last line, it does not start a new one."""
    return text.count("\n") + (1 if text and not text.endswith("\n") else 0)
