from typing import List, Optional
from app.core.config import settings
import logging

logger = logging.getLogger(__name__)


class NotificationService:
    """Service for sending notifications via multiple channels"""
    
    def __init__(self):
        self.twilio_client = None
        self.firebase_app = None
        
        # Initialize Twilio if credentials are available
        if settings.TWILIO_ACCOUNT_SID and settings.TWILIO_AUTH_TOKEN:
            try:
                from twilio.rest import Client
                self.twilio_client = Client(
                    settings.TWILIO_ACCOUNT_SID,
                    settings.TWILIO_AUTH_TOKEN
                )
                logger.info("Twilio client initialized")
            except Exception as e:
                logger.error(f"Failed to initialize Twilio: {e}")
        
        # Initialize Firebase if credentials are available
        if all([
            settings.FIREBASE_PROJECT_ID,
            settings.FIREBASE_API_KEY,
            settings.FIREBASE_AUTH_DOMAIN
        ]):
            try:
                import firebase_admin
                from firebase_admin import credentials, messaging
                
                if not firebase_admin._apps:
                    # For production, use a service account JSON file
                    # For now, we'll skip Firebase initialization
                    logger.info("Firebase initialization skipped - requires service account")
            except Exception as e:
                logger.error(f"Failed to initialize Firebase: {e}")
    
    def send_sms(
        self,
        phone_number: str,
        message: str
    ) -> bool:
        """Send SMS notification via Twilio"""
        if not self.twilio_client:
            logger.warning("Twilio client not initialized")
            return False
        
        try:
            message_obj = self.twilio_client.messages.create(
                body=message,
                from_=settings.TWILIO_PHONE_NUMBER,
                to=phone_number
            )
            logger.info(f"SMS sent to {phone_number}: {message_obj.sid}")
            return True
        except Exception as e:
            logger.error(f"Failed to send SMS to {phone_number}: {e}")
            return False
    
    def send_sos_alert(
        self,
        phone_number: str,
        user_name: str,
        maps_link: str,
        incident_type: Optional[str] = None
    ) -> bool:
        """Send SOS alert SMS to emergency contact"""
        message = f"""🚨 EMERGENCY ALERT

{user_name} may need immediate assistance.

Live Location:
{maps_link}
"""
        
        if incident_type:
            message += f"\nIncident Type: {incident_type}"
        
        message += "\n\nGenerated by Raven."
        
        return self.send_sms(phone_number, message)
    
    def send_verification_code(
        self,
        phone_number: str,
        code: str,
        contact_name: str
    ) -> bool:
        """Send verification code for emergency contact"""
        message = f"""Raven Verification

Your verification code for {contact_name} is: {code}

This code expires in 24 hours.
"""
        return self.send_sms(phone_number, message)
    
    def send_push_notification(
        self,
        device_token: str,
        title: str,
        body: str,
        data: Optional[dict] = None
    ) -> bool:
        """Send push notification via Firebase"""
        if not self.firebase_app:
            logger.warning("Firebase not initialized")
            return False
        
        try:
            from firebase_admin import messaging
            
            message = messaging.Message(
                notification=messaging.Notification(
                    title=title,
                    body=body
                ),
                token=device_token,
                data=data or {}
            )
            
            response = messaging.send(message)
            logger.info(f"Push notification sent: {response}")
            return True
        except Exception as e:
            logger.error(f"Failed to send push notification: {e}")
            return False
    
    def send_sos_push(
        self,
        device_token: str,
        user_name: str,
        maps_link: str
    ) -> bool:
        """Send SOS push notification"""
        return self.send_push_notification(
            device_token=device_token,
            title="🚨 Emergency Alert",
            body=f"{user_name} has triggered SOS. View location.",
            data={
                "type": "sos_alert",
                "maps_link": maps_link,
                "user_name": user_name
            }
        )
    
    def notify_emergency_contacts(
        self,
        contacts: List[dict],
        user_name: str,
        maps_link: str,
        incident_type: Optional[str] = None
    ) -> dict:
        """Notify multiple emergency contacts"""
        results = {
            "sms_success": 0,
            "sms_failed": 0,
            "total": len(contacts)
        }
        
        for contact in contacts:
            phone_number = contact.get("phone_number")
            if phone_number:
                success = self.send_sos_alert(
                    phone_number=phone_number,
                    user_name=user_name,
                    maps_link=maps_link,
                    incident_type=incident_type
                )
                if success:
                    results["sms_success"] += 1
                else:
                    results["sms_failed"] += 1
        
        return results


# Global notification service instance
notification_service = NotificationService()
