from app.analysis.filters import classify_path, looks_binary, looks_generated
from app.analysis.secrets import redact_secrets
from tests.fixtures.sample_repo import FAKE_AWS_KEY


def test_redacts_provider_tokens_and_marks_file():
    r = redact_secrets(f'AWS = "{FAKE_AWS_KEY}"\nx = 1\n')
    assert FAKE_AWS_KEY not in r.text and r.high_confidence and r.count == 1
    assert r.text.count("\n") == 2  # line count preserved


def test_pem_block_redacted_and_line_numbers_preserved():
    pem = "a = 1\n-----BEGIN RSA PRIVATE KEY-----\nMIIEabc\nxyz\n-----END RSA PRIVATE KEY-----\nb = 2"
    r = redact_secrets(pem)
    assert "MIIEabc" not in r.text and r.high_confidence
    assert len(r.text.split("\n")) == len(pem.split("\n"))
    assert r.text.endswith("b = 2")


def test_generic_assignment_redacted_without_marking_file():
    r = redact_secrets('api_key = "sup3rs3cretvalue99"\npassword = "changeme"\nsecret = os.environ["X"]\n')
    assert "sup3rs3cretvalue99" not in r.text
    assert "changeme" in r.text  # placeholders are not secrets
    assert not r.high_confidence and r.count == 1


def test_jwt_and_url_password():
    jwt = "eyJhbGciOiJIUzI1NiJ9.eyJzdWIiOiIxMjM0NTY3ODkwIn0.abcdefghijklmnop"
    assert jwt not in redact_secrets(f"t = '{jwt}'").text
    assert "hunter2hunter2" not in redact_secrets("u = 'postgresql://real:hunter2hunter2@prod/app'").text


def test_classify_paths():
    c = classify_path
    assert c("app/main.py").kind == "python"
    assert c("node_modules/x/index.js").reason == "dependency_dir"
    assert c("venv/lib/x.py").reason == "dependency_dir"
    assert c("build/x.py").reason == "build_artifact"
    assert c("a/__pycache__/x.py").reason == "cache"
    assert c("vendor/x.py").reason == "vendor"
    assert c("poetry.lock").reason == "lockfile"
    assert c(".env").reason == "secret_file" and c(".env.production").reason == "secret_file"
    assert c("keys/server.pem").reason == "secret_file" and c("id_rsa").reason == "secret_file"
    assert c(".env.example").kind == "env_template"
    assert c("logo.png").reason == "binary"
    assert c("x_pb2.py").reason == "generated"
    assert c("requirements.txt").kind == "support" and c("Dockerfile").kind == "support" and c("README.md").kind == "support"
    assert c("docs/guide.md").kind == "other"
    assert c("pkg.egg-info/PKG-INFO").reason == "build_artifact"


def test_binary_and_generated_detection():
    assert looks_binary(b"ab\x00cd") and not looks_binary(b"print(1)")
    assert looks_generated("# Code generated by protoc. DO NOT EDIT.\nx=1")
    assert not looks_generated("def f(): pass")
